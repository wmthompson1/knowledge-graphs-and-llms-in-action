---- ALTER PROCEDURE [dbo].[usp_BOE_BILLING_EME] (@STARTDATE DATE, @ENDDATE DATE) AS

SET NOCOUNT ON;
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED
SET DEADLOCK_PRIORITY LOW
IF OBJECT_ID('tempdb..#Results') IS NOT NULL DROP TABLE #Results;

IF OBJECT_ID('Staging.dbo.QueryB_Shape') IS NOT NULL DROP TABLE Staging.dbo.QueryB_Shape;

DECLARE @CHARGE FLOAT = (SELECT CHARGE FROM [sql-bi-1].LIVESupplemental.dbo.[BOE_Billing_Charges] WHERE [REPORT] = 'usp_BOE_BILLING_EME')
, @STARTDATE DATE = '6/1/2026'
, @ENDDATE DATE = '8/31/2026'
;

declare @cust_order_id nvarchar(50) = '524105'; -- '524105' -- '522706';

with results as (
SELECT SPROC 
	, [COST ITEM]
	-- cast( N'<nnn>' as nvarchar(20) 
	, POS
	, [PART NUMBER]
	, RAMAC
	, CASE
		WHEN SERVICE_CHARGE_ID = 'EX' THEN 1
		ELSE [BILLED QTY]
	END AS [BILLED QTY]
	, CASE
		WHEN SERVICE_CHARGE_ID = 'EX' THEN 0
		WHEN [EP_PART_ID] IS NOT NULL AND [EP_AMOUNT] <= 250 THEN 250 / NULLIF([BILLED QTY], 0) 
		WHEN [EP_PART_ID] IS NOT NULL AND [EP_AMOUNT] > 250 THEN [EP_AMOUNT] / NULLIF([BILLED QTY], 0)
		WHEN ((SUM(SORT_SETUP) + SUM(SORT_RUN)) * @CHARGE) < 250 THEN 250 / NULLIF([BILLED QTY], 0)
		ELSE ((SUM(SORT_SETUP) + SUM(SORT_RUN)) * @CHARGE) / NULLIF([BILLED QTY], 0) 
	END AS [UNIT PRICE]
	, CASE
		WHEN SERVICE_CHARGE_ID = 'EX' THEN 0
		WHEN [EP_PART_ID] IS NOT NULL AND [EP_AMOUNT] <= 250 THEN 250 
		WHEN [EP_PART_ID] IS NOT NULL AND [EP_AMOUNT] > 250 THEN [EP_AMOUNT]
		WHEN ((SUM(SORT_SETUP) + SUM(SORT_RUN)) * @CHARGE) < 250 THEN 250 
		ELSE ((SUM(SORT_SETUP) + SUM(SORT_RUN)) * @CHARGE)  
	END AS [EXTENDED DOLLARS]
	, [EXPEDITE DOLLARS]
	, [SPECIAL FEES]
	, 0 AS [SERVICE_FEE]
	, CASE
		WHEN SERVICE_CHARGE_ID = 'EX' THEN 0
		ELSE SUM(SORT_SETUP) 
	END AS [SETUP HOURS]
	, CASE
		WHEN SERVICE_CHARGE_ID = 'EX' THEN 0
		ELSE SUM(SORT_RUN) 
	END AS [RUN HOURS]
	, [EXPEDITE HOURS]
	, [PACK SLIPS / DATE]

	, [INVOICE ID]

		, STUFF(REPLACE('/' + CONVERT(NVARCHAR(15), INVOICED_DATE, 101), '/0', '/'), 1, 1, '') + CASE
		WHEN SERVICE_CHARGE_ID = 'EX' THEN ',EXPEDITE'
		WHEN [EP_PART_ID] IS NOT NULL AND [EP_AMOUNT] <= 250 THEN ',MIN LOT'
		WHEN ((SUM(SORT_SETUP) + SUM(SORT_RUN)) * @CHARGE) < 250 THEN ',MIN LOT'
		ELSE ',WRAP' 
	END AS COMMENTS
	-- , [COID]
	-- , [COLINE]
	--, '' AS COMMENTS
	, CAST('' AS varchar(1)) AS SORTATION
        , CUST_ORDER_ID
        , LINE_NO
FROM 
	(SELECT CASE
			WHEN CA.CITY IN ('HELENA', 'TUKWILA') THEN CA.CITY
			WHEN CO.CUSTOMER_ID IN ('BOE602') THEN CO.CUSTOMER_ID
			ELSE 'OTHER'
		END AS SPROC 
		, CASE
			WHEN COL.SERVICE_CHARGE_ID = 'EX' THEN 150
			ELSE 0 
		END AS [COST ITEM]
		-- , cast( N'900' as nvarchar(20) AS POS
		, CASE
			WHEN COL.SERVICE_CHARGE_ID = 'EX' THEN cast( N'900' as nvarchar(20))
			ELSE cast( N'2' as nvarchar(20))
		END AS POS
		-- , CASE
		-- 	WHEN RIGHT(CO.ID, 1) = 'A' AND LEN(REPLACE(CO.ID, 'A', '')) < 7 THEN CONVERT(NVARCHAR(50), CO.CUSTOMER_PO_REF) + N'A'
		-- 	WHEN LEN(REPLACE(CO.ID, 'A', '')) < 7 THEN CONVERT(NVARCHAR(50), CO.CUSTOMER_PO_REF)
		-- 	ELSE CONVERT(NVARCHAR(50), CO.ID)
		-- END AS RAMAC
		,CASE
			WHEN RIGHT(CONVERT(NVARCHAR(50), CO.ID), 1) = 'A'
			AND LEN(REPLACE(CONVERT(NVARCHAR(50), CO.ID), 'A', '')) < 7
				THEN CONVERT(NVARCHAR(50), CO.CUSTOMER_PO_REF) + N'A'
			WHEN LEN(REPLACE(CONVERT(NVARCHAR(50), CO.ID), 'A', '')) < 7
				THEN CONVERT(NVARCHAR(50), CO.CUSTOMER_PO_REF)
			ELSE CONVERT(NVARCHAR(50), CO.ID)
		END AS RAMAC
		, CASE
			WHEN LEN(REPLACE(CO.ID, 'A', '')) < 7 THEN CONVERT(NVARCHAR(50), CO.ID)
			ELSE CONVERT(NVARCHAR(50), CO.CUSTOMER_PO_REF)
		END AS COID
--		, 0 AS [EXPEDITE DOLLARS]
		, CASE
			WHEN COL.SERVICE_CHARGE_ID = 'EX' THEN COL.UNIT_PRICE
--			WHEN CO.CUSTOMER_ID IN ('BOE602') AND RIGHT(CO.CUSTOMER_PO_REF, 2) = 'SB' THEN 250
			ELSE 0 
		END AS [EXPEDITE DOLLARS]
		, 0 AS [SPECIAL FEES]
		, 0 AS [EXPEDITE HOURS]
		, LT.WORKORDER_BASE_ID
		, LT.HOURS_WORKED
		, EP.PART_ID AS [EP_PART_ID]
		, COL.LINE_NO AS [COLINE]
		, COL.SERVICE_CHARGE_ID
		, COL.UNIT_PRICE * COL.USER_ORDER_QTY AS [EP_AMOUNT]
		, CASE
			WHEN COL.SERVICE_CHARGE_ID = 'EX' THEN COL2.PART_ID 
			ELSE COL.PART_ID 
		END AS [PART NUMBER]
		, COL.TOTAL_SHIPPED_QTY AS [BILLED QTY]
		, LT.[TYPE]
		, LT.TRANSACTION_ID
		, CO.CUSTOMER_ID
		, SR.USER_1
		, SL.SHIPPED_QTY
		, S.INVOICE_ID AS [INVOICE ID]
		, S.INVOICED_DATE
		, S.PACKLIST_ID AS [PACK SLIPS / DATE]
		, SR.RESOURCE_ID
		, CASE
			WHEN LT.[TYPE] = 'S' THEN LT.HOURS_WORKED
			ELSE 0
		END AS SORT_SETUP
		, CASE
			WHEN LT.[TYPE] = 'R' THEN LT.HOURS_WORKED
			ELSE 0
		END AS SORT_RUN
        , COL.CUST_ORDER_ID
        , COL.LINE_NO
	FROM Dbo.SHIPPER S
	INNER JOIN Dbo.SHIPPER_LINE SL
		ON S.PACKLIST_ID = SL.PACKLIST_ID
	INNER JOIN Dbo.CUST_ORDER_LINE COL
		ON SL.CUST_ORDER_ID = COL.CUST_ORDER_ID
		AND SL.CUST_ORDER_LINE_NO = COL.LINE_NO
	INNER JOIN Dbo.CUSTOMER_ORDER CO
		ON COL.CUST_ORDER_ID = CO.ID
	INNER JOIN Dbo.CUST_ORDER_LINE COL2
		ON SL.CUST_ORDER_ID = COL2.CUST_ORDER_ID
--		AND SL.CUST_ORDER_LINE_NO = COL.LINE_NO
		AND COL2.SERVICE_CHARGE_ID IS NULL
	LEFT OUTER JOIN Dbo.DEMAND_SUPPLY_LINK DSL
		ON COL.CUST_ORDER_ID = DSL.DEMAND_BASE_ID
		AND COL.LINE_NO = DSL.DEMAND_SEQ_NO
	LEFT OUTER JOIN Dbo.WORK_ORDER WO
		ON DSL.SUPPLY_BASE_ID = WO.BASE_ID
		AND DSL.SUPPLY_LOT_ID = WO.LOT_ID
		AND DSL.SUPPLY_SPLIT_ID = WO.SPLIT_ID
	LEFT OUTER JOIN Dbo.LABOR_TICKET LT
		ON WO.BASE_ID = LT.WORKORDER_BASE_ID
		AND WO.LOT_ID = LT.WORKORDER_LOT_ID
		AND WO.SPLIT_ID = LT.WORKORDER_SPLIT_ID
		AND WO.SUB_ID = LT.WORKORDER_SUB_ID
		AND WO.[TYPE] = LT.WORKORDER_TYPE
	LEFT OUTER JOIN Dbo.SHOP_RESOURCE_SITE SR
		ON LT.RESOURCE_ID = SR.RESOURCE_ID
		--AND ISNULL(SR.USER_9, '') != 'BOE BILLING EXCLUDE'   -- Change
	LEFT OUTER JOIN CUST_ADDRESS CA
		ON CO.CUSTOMER_ID = CA.CUSTOMER_ID
		AND S.SHIP_TO_ADDR_NO = CA.ADDR_NO
	LEFT OUTER JOIN [sql-bi-1].LIVESupplemental.dbo.EME_Billing_Parts EP
		ON EP.PART_ID = COL.PART_ID
	WHERE 1=1
        and (@cust_order_id is null or @cust_order_id = COL.CUST_ORDER_ID)
        and SL.SHIPPED_QTY > 0
		AND ISNULL(WO.BASE_ID, '') NOT LIKE N'%R%'
		AND ISNULL(WO.PART_ID, '') NOT LIKE N'%REWORK%'
--> TT20211202: ADDED 602; REMOVED FROM 605
-->		AND CO.CUSTOMER_ID = N'BOEEME'
		AND CO.CUSTOMER_ID IN (N'BOEEME', N'BOE602')
		AND (S.INVOICED_DATE >= @STARTDATE AND S.INVOICED_DATE <= @ENDDATE)

--	AND CO.ID = '471811'
	) A
GROUP BY SPROC 
	, [COST ITEM]
	, POS
	, [PART NUMBER]
	, SERVICE_CHARGE_ID 
	, RAMAC
	, [BILLED QTY]
	, [INVOICE ID]
	, INVOICED_DATE
	, [PACK SLIPS / DATE]
	, [EXPEDITE DOLLARS]
	, [SPECIAL FEES]
	, [EXPEDITE HOURS]
	, [EP_PART_ID]
	, [EP_AMOUNT]
	, [COID]
	, [COLINE]
            , CUST_ORDER_ID
        , LINE_NO

UNION ALL
--> FOR 602SB EXPEDITES
SELECT SPROC 
	, [COST ITEM]
	
	, POS
	, [PART NUMBER]
	, RAMAC
	, 1 AS [BILLED QTY]
	, 0 AS [UNIT PRICE]
	, 0 AS [EXTENDED DOLLARS]
	, [EXPEDITE DOLLARS]
	, [SPECIAL FEES]
	, 0 AS [SERVICE_FEE]
	, 0 AS [SETUP HOURS]
	, 0 AS [RUN HOURS]
	, [EXPEDITE HOURS]
	, [PACK SLIPS / DATE]

	, [INVOICE ID]
		, STUFF(REPLACE('/' + CONVERT(NVARCHAR(15), INVOICED_DATE, 101), '/0', '/'), 1, 1, '') + ',EXPEDITE' AS COMMENTS
	-- , [COID]
	-- , [COLINE]
	--, '' AS COMMENTS
	, CAST('' AS varchar(1)) AS SORTATION
        , CUST_ORDER_ID
        , LINE_NO
FROM 
	(SELECT CASE
			WHEN CA.CITY IN ('HELENA', 'TUKWILA') THEN CA.CITY
			WHEN CO.CUSTOMER_ID IN ('BOE602') THEN CO.CUSTOMER_ID
			ELSE 'OTHER'
		END AS SPROC 
		--, 150 AS [COST ITEM]
		, CAST('150' AS NVARCHAR(20)) AS [COST ITEM]
		, cast( N'900' as nvarchar(20)) AS POS
		-- , CASE
		-- 	WHEN RIGHT(CO.ID, 1) = 'A' AND LEN(REPLACE(CO.ID, 'A', '')) < 7 THEN CONVERT(NVARCHAR(50), CO.CUSTOMER_PO_REF) + N'A'
		-- 	WHEN LEN(REPLACE(CO.ID, 'A', '')) < 7 THEN CONVERT(NVARCHAR(50), CO.CUSTOMER_PO_REF)
		-- 	ELSE CONVERT(NVARCHAR(50), CO.ID)
		-- END AS RAMAC
		,CASE
		WHEN RIGHT(CONVERT(NVARCHAR(50), CO.ID), 1) = 'A'
		AND LEN(REPLACE(CONVERT(NVARCHAR(50), CO.ID), 'A', '')) < 7
		THEN CONVERT(NVARCHAR(50), CO.CUSTOMER_PO_REF) + N'A'
		WHEN LEN(REPLACE(CONVERT(NVARCHAR(50), CO.ID), 'A', '')) < 7
		THEN CONVERT(NVARCHAR(50), CO.CUSTOMER_PO_REF)
		ELSE CONVERT(NVARCHAR(50), CO.ID)
		END AS RAMAC
		, CASE
			WHEN LEN(REPLACE(CO.ID, 'A', '')) < 7 THEN CONVERT(NVARCHAR(50), CO.ID)
			ELSE CONVERT(NVARCHAR(50), CO.CUSTOMER_PO_REF)
		END AS COID
		, CASE
			WHEN CO.CUSTOMER_ID IN ('BOE602') AND RIGHT(CONVERT(NVARCHAR(50), CO.CUSTOMER_PO_REF), 2) = 'SB' THEN 250
			ELSE 0 
		END AS [EXPEDITE DOLLARS]
		, 0 AS [SPECIAL FEES]
		, 0 AS [EXPEDITE HOURS]
		, 2 AS [COLINE]
		, COL.SERVICE_CHARGE_ID
		, COL.UNIT_PRICE * COL.USER_ORDER_QTY AS [EP_AMOUNT]
		, CASE
			WHEN COL.SERVICE_CHARGE_ID = 'EX' THEN COL2.PART_ID 
			ELSE COL.PART_ID 
		END AS [PART NUMBER]
		, COL.TOTAL_SHIPPED_QTY AS [BILLED QTY]
		, CO.CUSTOMER_ID
		, SL.SHIPPED_QTY
		, S.INVOICE_ID AS [INVOICE ID]
		, S.INVOICED_DATE
		, S.PACKLIST_ID AS [PACK SLIPS / DATE]
    -- task 20210818: added to have internal order id in the results for billing and gross margin processing
        , COL.CUST_ORDER_ID
        , COL.LINE_NO

	FROM Dbo.SHIPPER S
	INNER JOIN Dbo.SHIPPER_LINE SL
		ON S.PACKLIST_ID = SL.PACKLIST_ID
	INNER JOIN Dbo.CUST_ORDER_LINE COL
		ON SL.CUST_ORDER_ID = COL.CUST_ORDER_ID
		AND SL.CUST_ORDER_LINE_NO = COL.LINE_NO
	INNER JOIN Dbo.CUSTOMER_ORDER CO
		ON COL.CUST_ORDER_ID = CO.ID
	INNER JOIN Dbo.CUST_ORDER_LINE COL2
		ON SL.CUST_ORDER_ID = COL2.CUST_ORDER_ID
		AND COL2.SERVICE_CHARGE_ID IS NULL
	LEFT OUTER JOIN CUST_ADDRESS CA
		ON CO.CUSTOMER_ID = CA.CUSTOMER_ID
		AND S.SHIP_TO_ADDR_NO = CA.ADDR_NO
	WHERE 1=1
        and (@cust_order_id is null or @cust_order_id = COL.CUST_ORDER_ID)
        and SL.SHIPPED_QTY > 0
		AND CO.CUSTOMER_ID IN (N'BOEEME', N'BOE602')
		AND (S.INVOICED_DATE >= @STARTDATE AND S.INVOICED_DATE <= @ENDDATE)

		-- AND RIGHT(CONVERT(NVARCHAR(50), CO.CUSTOMER_PO_REF), 2) = 'SB'
		AND RIGHT(CONVERT(NVARCHAR(50), CO.CUSTOMER_PO_REF), 2) = 'SB'
--	AND CO.ID = '471811'
	) A
GROUP BY SPROC 
	, [COST ITEM]
	, POS
	, [PART NUMBER]
	, SERVICE_CHARGE_ID 
	, RAMAC
	, [BILLED QTY]
	, [INVOICE ID]
	, INVOICED_DATE
	, [PACK SLIPS / DATE]
	, [EXPEDITE DOLLARS]
	, [SPECIAL FEES]
	, [EXPEDITE HOURS]
	, [EP_AMOUNT]
	-- , [COID]
	-- , [COLINE]
    , CUST_ORDER_ID
    , LINE_NO
)
select 
   r.CUST_ORDER_ID
  ,r.LINE_NO 
  ,r.pos
  ,r.[EXPEDITE DOLLARS]
  -- Code to verify grain ias correct and not duplicating rows
  ,row_number() over (partition by r.CUST_ORDER_ID, r.LINE_NO order by r.[RAMAC]) as rownum
  ,r.[UNIT PRICE], r.[EXTENDED DOLLARS], r.[SETUP HOURS], r.[RUN HOURS], r.[EXPEDITE HOURS], r.[PACK SLIPS / DATE]
, r.[INVOICE ID], r.COMMENTS, r.SORTATION, r.CUST_ORDER_ID, r.LINE_NO 

, x.CUST_ORDER_ID, x.INVOICE_ID, x.CUST_ORDER_ID, x.COL_LINE_NO, x.ORDER_QTY, x.UNIT_PRICE  ,x.INVOICE_AMT
, x.PACKLIST_ID, x.PACKLIST_LINE_NO, x.INVOICE_AMT

from results r
join LIVESupplemental.dbo.Feed_01_Core_Intermediate_complement_OT x
-- on r.CUST_ORDER_ID = x.CUST_ORDER_ID
-- and r.LINE_NO = x.COL_LINE_NO
-- and r.[INVOICE ID] = x.INVOICE_ID
on r.[PACK SLIPS / DATE] = x.PACKLIST_ID
ORDER BY r.[RAMAC];

SELECT x.CUST_ORDER_ID, x.INVOICE_ID, x.CUST_ORDER_ID, x.COL_LINE_NO, x.ORDER_QTY, x.UNIT_PRICE  ,x.INVOICE_AMT
 , x.PACKLIST_ID, x.PACKLIST_LINE_NO, x.INVOICE_AMT
FROM 
LIVESupplemental.dbo.Feed_01_Core_Intermediate_complement_OT x
WHERE 1=1
 AND CUST_ORDER_ID = '524105'  -- -- '524105'
