--DECLARE @End2   datetime = '2026-08-31 00:00:00';

DECLARE @Start1 datetime = '2026-02-01 00:00:00';
DECLARE @End1   datetime = '2026-08-27 00:00:00';
DECLARE @Start2 datetime = '2026-02-01 00:00:00';
DECLARE @End2   datetime = '2026-08-27 00:00:00';
declare @x nvarchar(50) =  ''; -- '508079';
declare @y nvarchar(50) =  'boe609'; -- '508079';

SELECT
    O.ID CUST_ORDER_ID,
        o.[STATUS] order_status,
    O.CUSTOMER_PO_REF,
    C.ID CUSTOMER_ID,
    C.NAME,
    L.PART_ID,
    LK.SUPPLY_TYPE,
    LK.SUPPLY_BASE_ID,
    LK.SUPPLY_LOT_ID,
    LK.SUPPLY_SPLIT_ID,
    LK.SUPPLY_SEQ_NO,
    LK.SUPPLY_NO,
    L.MISC_REFERENCE,
    L.PRODUCT_CODE,
    L.COMMODITY_CODE,
    O.SALESREP_ID,
    O.TERRITORY,
    ISNULL(L.DESIRED_SHIP_DATE, O.DESIRED_SHIP_DATE) DESIRED_SHIP_DATE,
    ISNULL(L.PROMISE_DATE, O.PROMISE_DATE) PROMISE_DATE,
    ISNULL(L.PROMISE_DEL_DATE, O.PROMISE_DEL_DATE) PROMISE_DEL_DATE,
    L.USER_ORDER_QTY,
    0 AS  USER_SHIPPED_QTY,
    L.TOTAL_USR_SHIP_QTY,

    L.UNIT_PRICE,
    L.TRADE_DISC_PERCENT,
    L.CUSTOMER_PART_ID,
    L.GL_REVENUE_ACCT_ID,
    L.LINE_NO COL_LINE_NO,
    L.SELLING_UM,

    0 AS DEL_SCHED_LINE_NO, -- n/a
    L.WAREHOUSE_ID,
    L.SITE_ID,
    L.ORDER_QTY,
    L.TOTAL_SHIPPED_QTY
FROM CUSTOMER_ORDER O
JOIN CUSTOMER C
    ON O.CUSTOMER_ID = C.ID
JOIN CUST_ORDER_LINE L
    ON L.CUST_ORDER_ID = O.ID
LEFT JOIN DEMAND_SUPPLY_LINK LK
    ON LK.DEMAND_TYPE = N'CO'
   AND LK.DEMAND_BASE_ID = L.CUST_ORDER_ID
   AND LK.DEMAND_SEQ_NO = L.LINE_NO
WHERE 1=1
--and c.id = @y
 AND CUST_ORDER_ID IN (
 '002064831'
,'002064829'
,'002061274'
,'002059559'
,'002057553'
,'002066912'
)
--and L.ORDER_QTY > L.TOTAL_SHIPPED_QTY
  --AND (
  --      (O.STATUS IN (N'R', N'F') AND L.LINE_STATUS = N'A')
  --      OR (L.LINE_STATUS IN (N'R', N'F'))
  --    )
  AND NOT EXISTS (
        SELECT 1
        FROM CUST_LINE_DEL DS
        WHERE DS.CUST_ORDER_ID = L.CUST_ORDER_ID
          AND DS.CUST_ORDER_LINE_NO = L.LINE_NO
      )
  AND ISNULL(L.DESIRED_SHIP_DATE, O.DESIRED_SHIP_DATE) BETWEEN @Start1 AND @End1
  AND L.SITE_ID IN (N'SK01')

UNION ALL

SELECT
    O.ID,
    o.[STATUS] order_status,
    O.CUSTOMER_PO_REF,
    C.ID,
    C.NAME,
    L.PART_ID,
    LK.SUPPLY_TYPE,
    LK.SUPPLY_BASE_ID,
    LK.SUPPLY_LOT_ID,
    LK.SUPPLY_SPLIT_ID,
    LK.SUPPLY_SEQ_NO,
    LK.SUPPLY_NO,
    L.MISC_REFERENCE,
    L.PRODUCT_CODE,
    L.COMMODITY_CODE,
    O.SALESREP_ID,
    O.TERRITORY,
    ISNULL(DS.DESIRED_SHIP_DATE, ISNULL(L.DESIRED_SHIP_DATE, O.DESIRED_SHIP_DATE)),
    ISNULL(L.PROMISE_DATE, O.PROMISE_DATE),
    ISNULL(L.PROMISE_DEL_DATE, O.PROMISE_DEL_DATE),
    L.USER_ORDER_QTY,
    DS.USER_ORDER_QTY,
    ISNULL(DS.USER_SHIPPED_QTY, 0) USER_SHIPPED_QTY,
    L.UNIT_PRICE,

    L.TRADE_DISC_PERCENT,
    L.CUSTOMER_PART_ID,
    L.GL_REVENUE_ACCT_ID,
    L.LINE_NO COL_LINE_NO,
    L.SELLING_UM,

    DS.DEL_SCHED_LINE_NO,
    ISNULL(DS.WAREHOUSE_ID, L.WAREHOUSE_ID),
    L.SITE_ID,
    DS.ORDER_QTY,
    DS.SHIPPED_QTY
FROM CUST_ORDER_LINE L
JOIN CUSTOMER_ORDER O
    ON L.CUST_ORDER_ID = O.ID
JOIN CUSTOMER C
    ON O.CUSTOMER_ID = C.ID
JOIN CUST_LINE_DEL DS
    ON DS.CUST_ORDER_ID = L.CUST_ORDER_ID
   AND DS.CUST_ORDER_LINE_NO = L.LINE_NO
LEFT JOIN DEMAND_SUPPLY_LINK LK
    ON LK.DEMAND_TYPE = N'CD'
   AND LK.DEMAND_BASE_ID = DS.CUST_ORDER_ID
   AND LK.DEMAND_SEQ_NO = DS.CUST_ORDER_LINE_NO
   AND LK.DEMAND_NO = DS.DEL_SCHED_LINE_NO
WHERE 1=1
  and c.id = @y
  --and DS.ORDER_QTY > ISNULL(DS.SHIPPED_QTY, 0)
  AND DS.LINE_STATUS <> N'C'
  --AND (
  --      (O.STATUS IN (N'R', N'F') AND L.LINE_STATUS = N'A')
  --      OR (L.LINE_STATUS IN (N'R', N'F'))
  --    )
  AND ISNULL(DS.DESIRED_SHIP_DATE, ISNULL(L.DESIRED_SHIP_DATE, O.DESIRED_SHIP_DATE))
      BETWEEN @Start2 AND @End2
  AND L.SITE_ID IN (N'SK01')

ORDER BY 31, 17, 1;