SELECT 
BUSSTREAM,
CASE
	WHEN BUSSTREAM = 'CMP-MFG' THEN 'TOTAL-MFG'
	WHEN BUSSTREAM = 'CMP-FIN' THEN 'TOTAL-FIN'
	ELSE BUSSTREAM
END AS UPDATEDBUSSTREAM
, 'TOTAL' AS BUSSTREAM
, 'TOTAL' AS [TARGET TOTAL]

, [DATE]
, TARGET AS [TOTAL INVOICE]
FROM [LIVESupplemental].[dbo].[Plant_Shipment_Forecast] PSF
WHERE 1=1 
-- and BUSSTREAM IN ('CMP-MFG', 'CMP-FIN') 
AND DATE >= DATEADD(yy, -2, DATEADD(yy, DATEDIFF(yy, 0, GETDATE()), 0) )
