			WHEN B.BUS_STREAM = 'MFG' AND FIN_COUNT > 2 THEN 'MFGFIN'
			WHEN B.BUS_STREAM = 'FIN' AND MFG_COUNT > 2 THEN 'FINMFG'
			ELSE B.BUS_STREAM
		END AS 'UPD_BUS_STREAM'
	FROM CTE_BASE B
	LEFT OUTER JOIN CTE_PIVOT P WITH (NOLOCK) ON B.BASE_ID = P.BASE_ID
		AND B.LOT_ID = P.LOT_ID AND B.SPLIT_ID = P.SPLIT_ID AND B.SUB_ID = P.SUB_ID
)
