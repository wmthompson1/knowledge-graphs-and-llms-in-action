					WHEN COL.LINE_STATUS = 'C' THEN 0
					WHEN CO.[STATUS] = 'C' THEN 0
					WHEN COL.ORDER_QTY < COL.TOTAL_SHIPPED_QTY THEN 0
					ELSE COL.ORDER_QTY - COL.TOTAL_SHIPPED_QTY
