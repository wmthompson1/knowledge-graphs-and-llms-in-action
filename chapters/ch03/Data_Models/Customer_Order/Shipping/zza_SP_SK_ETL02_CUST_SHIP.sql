					WHEN CHARINDEX('NRE VOI', COL.MISC_REFERENCE) > 0 THEN 'SERVICE CHARGE'
					WHEN CHARINDEX('SHIPPING CHARGE', COL.MISC_REFERENCE) > 0 THEN 'SERVICE CHARGE'
