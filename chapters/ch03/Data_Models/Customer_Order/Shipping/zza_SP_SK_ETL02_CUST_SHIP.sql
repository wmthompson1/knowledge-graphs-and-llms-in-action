				, ISNULL(RL.AMOUNT, 0) AS INVOICE_AMT
				, CASE
					WHEN LTRIM(RTRIM(RIGHT(R.INVOICE_ID,1))) = 'M' THEN 0
					ELSE RL.QTY
				END AS INVOICE_QTY
				--> tt20220117: per AnnW email
				, CASE
					WHEN ISNULL(CO.CUSTOMER_ID, '') != 'BOE609' AND P.PLANNER_USER_ID = 'FIN' THEN CONVERT(DATE, DATEADD(DD, 1, ISNULL(COL.DESIRED_SHIP_DATE, CO.DESIRED_SHIP_DATE))) 
					WHEN ISNULL(CO.CUSTOMER_ID, '') = 'BOE609' AND LEFT(P.BUYER_USER_ID, 2) = '59' THEN CONVERT(DATE, DATEADD(DD, 7, CO.ORDER_DATE))
					WHEN ISNULL(CO.CUSTOMER_ID, '') = 'BOE609' AND RTRIM(LTRIM(P.PLANNER_USER_ID)) = 'FIN-HOURLY' THEN CONVERT(DATE, DATEADD(DD, 7, CO.ORDER_DATE))
					WHEN ISNULL(CO.CUSTOMER_ID, '') = 'BOE609' AND LEFT(P.BUYER_USER_ID, 2) = '09' THEN CONVERT(DATE, DATEADD(DD, 25, CO.ORDER_DATE))
					WHEN ISNULL(CO.CUSTOMER_ID, '') = 'BOE609' AND LEFT(P.PLANNER_USER_ID, 10) = 'MFG-HOURLY' THEN CONVERT(DATE, DATEADD(DD, 25, CO.ORDER_DATE))
					ELSE CONVERT(DATE, ISNULL(COL.DESIRED_SHIP_DATE, CO.DESIRED_SHIP_DATE))
				END AS ADJ_DUE_DATE
			FROM CUST_ORDER_LINE COL WITH (NOLOCK)
			INNER JOIN CUSTOMER_ORDER CO WITH (NOLOCK) ON CO.ID = COL.CUST_ORDER_ID
			LEFT OUTER JOIN PART P WITH (NOLOCK) ON COL.PART_ID = P.ID
			LEFT OUTER JOIN PART P2 WITH (NOLOCK) ON COL.MISC_REFERENCE = P2.ID
			-->		AND COL.PART_ID IS NULL  --< DON'T KNOW IF I NEED THIS
			LEFT OUTER JOIN SHIPPER_LINE SL WITH (NOLOCK) ON COL.CUST_ORDER_ID = SL.CUST_ORDER_ID
				AND COL.LINE_NO = SL.CUST_ORDER_LINE_NO AND SL.SHIPPED_QTY <> 0
			LEFT OUTER JOIN SHIPPER S WITH (NOLOCK) ON SL.PACKLIST_ID = S.PACKLIST_ID
			LEFT OUTER JOIN RECEIVABLE_LINE RL WITH (NOLOCK) ON SL.PACKLIST_ID = RL.PACKLIST_ID
				AND SL.LINE_NO = RL.PACKLIST_LINE_NO
			LEFT OUTER JOIN RECEIVABLE R WITH (NOLOCK) ON RL.INVOICE_ID = R.INVOICE_ID
			LEFT OUTER JOIN USER_DEF_FIELDS UDF WITH (NOLOCK) ON UDF.DOCUMENT_ID = CO.CUSTOMER_ID
				AND PROGRAM_ID = 'VMCUSMNT' AND UDF.ID = 'UDF-0000072'
			LEFT OUTER JOIN USER_DEF_FIELDS UDF1 WITH (NOLOCK) ON UDF1.DOCUMENT_ID = P.ID
				AND UDF1.PROGRAM_ID = 'VMPRTMNT' AND UDF1.ID = 'UDF-0000035'
			-- LEFT JOIN  LIVESupplemental.dbo.Feed_02_Core_BOE_Billing boe
			--     on sl.PACKLIST_ID = boe.[PackSlip]
	WHERE COALESCE(R.INVOICE_DATE, S.SHIPPED_DATE, COL.DESIRED_SHIP_DATE, CO.DESIRED_SHIP_DATE) >= @StartDate
) A
LEFT OUTER  JOIN DEMAND_SUPPLY_LINK DSL WITH (NOLOCK) ON DSL.DEMAND_TYPE = 'CO'
	AND DSL.DEMAND_BASE_ID = A.CUST_ORDER_ID AND DSL.DEMAND_SEQ_NO = A.COL_LINE_NO
LEFT OUTER JOIN WORK_ORDER WO WITH (NOLOCK) ON DSL.SUPPLY_TYPE = 'WO' 
	AND DSL.SUPPLY_BASE_ID = WO.BASE_ID AND DSL.SUPPLY_LOT_ID = WO.LOT_ID
	AND DSL.SUPPLY_SPLIT_ID = WO.SPLIT_ID AND DSL.SUPPLY_SUB_ID = WO.SUB_ID 
	AND WO.[TYPE] = 'W'
)
