					WHEN CHARINDEX('FAI CHARGE', COL.MISC_REFERENCE) > 0 THEN COL.MISC_REFERENCE
					WHEN CHARINDEX('FAI COST', COL.MISC_REFERENCE) > 0 THEN COL.MISC_REFERENCE
