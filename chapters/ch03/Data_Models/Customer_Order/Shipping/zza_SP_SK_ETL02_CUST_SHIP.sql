				, CASE
					WHEN COL.SERVICE_CHARGE_ID IS NOT NULL THEN 'SERVICE CHARGE'
					--> tt20210201
					WHEN CHARINDEX('NRE PROGRAMMING', COL.MISC_REFERENCE) > 0 THEN 'SERVICE CHARGE'
					WHEN CHARINDEX('PROGRAMMING', COL.MISC_REFERENCE) > 0 THEN 'SERVICE CHARGE'
