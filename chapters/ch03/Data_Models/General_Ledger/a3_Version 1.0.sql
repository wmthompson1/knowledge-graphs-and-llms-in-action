-- ============================================================================
-- 2. Component deltas from detail tables (latest dist minus previous dist)
--
-- Approach:
--  Regression
-- Note :
-- If journals are prepared out of order, Costing Tools will display an exception as the values used from the _DETAIL tables are based on the last DIST_NO.

-- Additional information re:  DIST_NO
-- When journals are prepared in Costing Utilities, the _DETAIL and _DIST tables are built.  If the transaction has had a distribution previously, any difference between DIST_NOs is journalized.

-- Example using a work order receipt
-- Work order value = 100.00; work order is received
-- DIST_NO 1 = 100.00

-- Additional material is issued to the work order, value = 25.00
-- DIST_NO 2 = 125.00
-- Journal is created for 25.00

-- Additional material is issued to the work order, value = 10.00
-- DIST_NO 3 = 135.00
-- Journal is created for 10.00

-- DIST_NOs are generated by Costing sequentially.  If a DIST_NO is missing, in the above example, there is a DIST_NO = 1 and DIST_NO = 3, DIST_NO = 2 was deleted from the table directly.  

--
-- This handles any number of dist_no values per work order and avoids
-- joining current rows to multiple previous rows.
-- ============================================================================



WITH labor_accum AS
(
    SELECT
         WORKORDER_TYPE
        ,WORKORDER_BASE_ID
        ,WORKORDER_LOT_ID
        ,WORKORDER_SPLIT_ID
        ,WORKORDER_SUB_ID
        ,DIST_NO
		,DR_LAB_GL_ACCT_ID, DR_BUR_GL_ACCT_ID, CR_LAB_GL_ACCT_ID, CR_BUR_GL_ACCT_ID
        ,SUM(ACT_LABOR_COST)  AS ACT_LABOR_COST
        ,SUM(ACT_BURDEN_COST) AS ACT_BURDEN_COST
    FROM Live.dbo.WIP_LABOR_DETAIL
    WHERE WORKORDER_BASE_ID = @WORKORDER_BASE_ID
    GROUP BY
         WORKORDER_TYPE
        ,WORKORDER_BASE_ID
        ,WORKORDER_LOT_ID
        ,WORKORDER_SPLIT_ID
        ,WORKORDER_SUB_ID
        ,DIST_NO

		,DR_LAB_GL_ACCT_ID, DR_BUR_GL_ACCT_ID, CR_LAB_GL_ACCT_ID, CR_BUR_GL_ACCT_ID
),
labor_delta AS
(
    SELECT
         WORKORDER_TYPE
        ,WORKORDER_BASE_ID
        ,WORKORDER_LOT_ID
        ,WORKORDER_SPLIT_ID
        ,WORKORDER_SUB_ID
        ,DIST_NO
		,DR_LAB_GL_ACCT_ID, DR_BUR_GL_ACCT_ID, CR_LAB_GL_ACCT_ID, CR_BUR_GL_ACCT_ID

        ,ACT_LABOR_COST
        ,LAG(ACT_LABOR_COST) OVER
         (
             PARTITION BY
                 WORKORDER_TYPE,
                 WORKORDER_BASE_ID,
                 WORKORDER_LOT_ID,
                 WORKORDER_SPLIT_ID,
                 WORKORDER_SUB_ID
             ORDER BY DIST_NO
         ) AS PREV_LABOR_COST

        ,ACT_BURDEN_COST
        ,LAG(ACT_BURDEN_COST) OVER
         (
             PARTITION BY
                 WORKORDER_TYPE,
                 WORKORDER_BASE_ID,
                 WORKORDER_LOT_ID,
                 WORKORDER_SPLIT_ID,
                 WORKORDER_SUB_ID
             ORDER BY DIST_NO
         ) AS PREV_BURDEN_COST
    FROM labor_accum
), labor_delta_dist_no as (
SELECT
     WORKORDER_TYPE
    ,WORKORDER_BASE_ID
    ,WORKORDER_LOT_ID
    ,WORKORDER_SPLIT_ID
    ,WORKORDER_SUB_ID
    ,DIST_NO

	,DR_LAB_GL_ACCT_ID, DR_BUR_GL_ACCT_ID, CR_LAB_GL_ACCT_ID, CR_BUR_GL_ACCT_ID

    ,ACT_LABOR_COST
    ,PREV_LABOR_COST

    ,ACT_LABOR_COST
        - ISNULL(PREV_LABOR_COST,0) AS LABOR_DELTA

    ,ACT_BURDEN_COST
        - ISNULL(PREV_BURDEN_COST,0) AS BURDEN_DELTA
FROM labor_delta
---ORDER BY DIST_NO
)
select

    coalesce(l.WORKORDER_TYPE, null,null)   						as WORKORDER_TYPE,
    coalesce(l.WORKORDER_BASE_ID, null,null)  						as WORKORDER_BASE_ID,
    coalesce(l.WORKORDER_LOT_ID, null,null)      					as WORKORDER_LOT_ID,
    coalesce(l.WORKORDER_SPLIT_ID, null,null)  						as WORKORDER_SPLIT_ID,
    coalesce(l.WORKORDER_SUB_ID, null,null)      					as WORKORDER_SUB_ID,
	--
    sum(isnull(l.labor_delta, 0)  )                                       as labor_delta,
    sum(isnull(l.burden_delta, 0) )                                       as burden_delta
	--
	--
	--
	,DR_LAB_GL_ACCT_ID  ---, DR_BUR_GL_ACCT_ID, CR_LAB_GL_ACCT_ID, CR_BUR_GL_ACCT_ID
from labor_delta_dist_no l
group by 
l.WORKORDER_TYPE ,l.WORKORDER_BASE_ID 
,l.WORKORDER_LOT_ID , l.WORKORDER_SPLIT_ID 
    ,l.WORKORDER_SUB_ID 
	,DR_LAB_GL_ACCT_ID   ---, DR_BUR_GL_ACCT_ID, CR_LAB_GL_ACCT_ID, CR_BUR_GL_ACCT_ID
;