DECLARE @ORDER_ID varchar(20) = '194174';

;WITH CTE_UDF_VMDOCMNT AS
(
    SELECT DOCUMENT_ID,
        MAX(CASE WHEN ID = 'UDF-0000032' THEN STRING_VAL END) AS ADCN
    FROM Live.dbo.USER_DEF_FIELDS
    WHERE PROGRAM_ID = 'VMDOCMNT'
    GROUP BY DOCUMENT_ID
), CTE_UDF_VMPRTMNT AS
(
    SELECT DOCUMENT_ID,
        MAX(CASE WHEN ID = 'UDF-0000040' THEN BOOL_VAL END) AS ITAR_PART,
        MAX(CASE WHEN ID = 'UDF-0000082' THEN STRING_VAL END) AS CONTROLLED_CODE,
        MAX(CASE WHEN ID = 'UDF-0000084' THEN STRING_VAL END) AS CERT_REQ,
        MAX(CASE WHEN ID = 'UDF-0000085' THEN STRING_VAL END) AS USED_ON,
        MAX(CASE WHEN ID = 'UDF-0000091' THEN BOOL_VAL END) AS HAS_PRT_LIMITED,
        MAX(CASE WHEN ID = 'UDF-0000101' THEN STRING_VAL END) AS PART_QCNOTES,
        MAX(CASE WHEN ID = 'UDF-00115' THEN BOOL_VAL END) AS SUPPLIER_CONTROLLED_DRAWING
    FROM Live.dbo.USER_DEF_FIELDS
    WHERE PROGRAM_ID = 'VMPRTMNT'
    GROUP BY DOCUMENT_ID
), CTE_UDF_VMVNDMNT AS
(
    SELECT DOCUMENT_ID,
        MAX(CASE WHEN ID = 'UDF-0000090' THEN BOOL_VAL END) AS HAS_VND_LIMITED,
        MAX(CASE WHEN ID = 'UDF-0000102' THEN STRING_VAL END) AS VENDOR_QCNOTES
    FROM Live.dbo.USER_DEF_FIELDS
    WHERE PROGRAM_ID = 'VMVNDMNT'
    GROUP BY DOCUMENT_ID
), CTE_UDF_VMPURENT AS
(
    SELECT DOCUMENT_ID,
        MAX(CASE WHEN ID = 'UDF-0000100' THEN BOOL_VAL END) AS PREPAID_CC
    FROM Live.dbo.USER_DEF_FIELDS
    WHERE PROGRAM_ID = 'VMPURENT'
    GROUP BY DOCUMENT_ID
), CTE_UDF_VMMFGWIN_OP AS
(
    SELECT DOCUMENT_ID,
        MAX(CASE WHEN ID = 'UDF-0000074' THEN STRING_VAL END) AS UDF_STRINGV_WO
    FROM Live.dbo.USER_DEF_FIELDS
    WHERE PROGRAM_ID = 'VMMFGWIN_OP'
    GROUP BY DOCUMENT_ID
), CTE_DOCS AS
(
    SELECT
        DRW.WORKORDER_BASE_ID,
        DRW.WORKORDER_LOT_ID,
        DRW.WORKORDER_SPLIT_ID,
        DRW.WORKORDER_SUB_ID,
        DRW.WORKORDER_TYPE,
        DRW.SEQUENCE_NO,
        D.ID
            + CASE WHEN D.REVISION_ID IS NULL THEN ' / REV: ' ELSE ' / REV: ' + D.REVISION_ID END
            + CASE WHEN DOC_UDF.ADCN IS NULL THEN ' / ADCN: ' ELSE ' / ADCN: ' + DOC_UDF.ADCN END
            + CHAR(10) AS DOCUMENT_ID
    FROM DEMAND_SUPPLY_LINK DSL
    INNER JOIN WORK_ORDER WO
        ON DSL.DEMAND_BASE_ID = WO.BASE_ID
       AND DSL.DEMAND_LOT_ID = WO.LOT_ID
       AND WO.SUB_ID = '0'
    INNER JOIN DOCUMENT_REF_WO DRW
        ON DRW.WORKORDER_BASE_ID = WO.PART_ID
       AND (DRW.WORKORDER_SUB_ID = DSL.DEMAND_SUB_ID OR (DRW.WORKORDER_SUB_ID = 0 AND DRW.SEQUENCE_NO = 0))
    INNER JOIN DOCUMENT D
        ON DRW.DOCUMENT_ID = D.ID
    LEFT JOIN CTE_UDF_VMDOCMNT DOC_UDF
        ON DOC_UDF.DOCUMENT_ID = D.ID
    WHERE DSL.SUPPLY_BASE_ID = @ORDER_ID

    UNION ALL

    SELECT
        DRW.WORKORDER_BASE_ID,
        DRW.WORKORDER_LOT_ID,
        DRW.WORKORDER_SPLIT_ID,
        DRW.WORKORDER_SUB_ID,
        DRW.WORKORDER_TYPE,
        DRW.SEQUENCE_NO,
        D.ID
            + CASE WHEN D.REVISION_ID IS NULL THEN ' / REV: ' ELSE ' / REV: ' + D.REVISION_ID END
            + CASE WHEN DOC_UDF.ADCN IS NULL THEN ' / ADCN: ' ELSE ' / ADCN: ' + DOC_UDF.ADCN END
            + CHAR(10) AS DOCUMENT_ID
    FROM DEMAND_SUPPLY_LINK DSL
    INNER JOIN WORK_ORDER LEG_WO
        ON LEG_WO.TYPE = 'W'
       AND LEG_WO.BASE_ID = DSL.DEMAND_BASE_ID
       AND LEG_WO.LOT_ID = DSL.DEMAND_LOT_ID
       AND LEG_WO.SPLIT_ID = DSL.DEMAND_SPLIT_ID
       AND LEG_WO.SUB_ID = DSL.DEMAND_SUB_ID
    INNER JOIN DOCUMENT_REF_WO DRW
        ON DRW.WORKORDER_TYPE = LEG_WO.TYPE
       AND DRW.WORKORDER_BASE_ID = LEG_WO.BASE_ID
       AND DRW.WORKORDER_LOT_ID = LEG_WO.LOT_ID
       AND DRW.WORKORDER_SPLIT_ID = LEG_WO.SPLIT_ID
       AND DRW.WORKORDER_SUB_ID = LEG_WO.SUB_ID
    INNER JOIN DOCUMENT D
        ON DRW.DOCUMENT_ID = D.ID
    LEFT JOIN CTE_UDF_VMDOCMNT DOC_UDF
        ON DOC_UDF.DOCUMENT_ID = D.ID
    WHERE DSL.SUPPLY_BASE_ID = @ORDER_ID
), CTE_BASE AS
(
    SELECT
        PO.ID AS ORDER_ID,
        POL.LINE_NO,
        PO.ORDER_DATE,
        PO.BUYER,
        PO.SHIP_VIA,
        PO.FREE_ON_BOARD,
        EE.EMAIL_ADDR AS BUYER_EMAIL,
        PO.TOTAL_AMT_ORDERED AS PO_TOTAL,
        CASE WHEN ISNULL(PO_UDF.PREPAID_CC, 0) = 1 THEN 'Prepaid via CC' ELSE T.DESCRIPTION END AS TERMS,
        PO.VENDOR_ID,
        V.NAME AS VENDOR_NAME,
        V.ADDR_1 AS VENDOR_ADDR_1,
        V.ADDR_2 AS VENDOR_ADDR_2,
        V.ADDR_3 AS VENDOR_ADDR_3,
        CASE WHEN V.COUNTRY IN ('US', 'USA', 'UNITED STATES') THEN V.CITY + ', ' + V.STATE + '  ' + V.ZIPCODE ELSE V.ADDR_3 + ' ' + V.COUNTRY + ' ' + V.ZIPCODE END AS VENDOR_CTSZ,
        PO.CONTACT_PHONE AS VENDOR_PHONE,
        PO.CONTACT_FAX AS VENDOR_FAX,
        VENDOR_UDF.VENDOR_QCNOTES,
        STA.NAME AS SHIPTO_NAME,
        STA.ADDR_1 AS SHIPTO_ADDR_1,
        STA.CITY AS SHIPTO_CITY,
        STA.STATE AS SHIPTO_STATE,
        STA.ZIPCODE AS SHIPTO_ZIPCODE,
        STA.COUNTRY AS SHIPTO_COUNTRY,
        POL.PART_ID,
        POL.USER_1 AS POL_USER_1,
        P.DESCRIPTION AS PART_DESCRIPTION,
        DBO.SFNWONUMFORMAT(DSL.DEMAND_BASE_ID, DSL.DEMAND_LOT_ID, DSL.DEMAND_SPLIT_ID, DSL.DEMAND_SUB_ID) AS WORKORDER,
        POL.VENDOR_PART_ID,
        POL.USER_ORDER_QTY,
        POL.PURCHASE_UM,
        POL.UNIT_PRICE,
        ISNULL(POL.DESIRED_RECV_DATE, PO.DESIRED_RECV_DATE) AS POL_DESIRED_RECV_DATE,
        POL.TOTAL_AMT_ORDERED,
        POL.MFG_NAME,
        POL.MFG_PART_ID,
        POL.USER_2 AS POL_USER_2,
        CASE WHEN POL.USER_2 = 'Y' THEN ISNULL(POL.TOTAL_AMT_ORDERED, 0) * .1 ELSE 0 END AS POL_TAX,
        PART_UDF.PART_QCNOTES,
        PART_UDF.ITAR_PART,
        CASE WHEN PART_UDF.ITAR_PART = 1 AND V.USER_1 = 'Y' AND ISNULL(V.USER_4, '') <> '' THEN 'ITAR' END AS ISITAR,
        CASE
            WHEN PART_UDF.CONTROLLED_CODE = 'SPECIFICATION CONTROLLED' THEN 'Product must be manufactured by an approved supplier listed in stated specification'
            WHEN PART_UDF.CONTROLLED_CODE = 'CONTROLLED' THEN 'Product is a Controlled Part'
            WHEN PART_UDF.CONTROLLED_CODE = 'QPL CONTROLLED' THEN 'Product must be from a QPL-approved manufacturer'
        END AS CONTROLLED_TEXT,
        PART_UDF.CERT_REQ,
        PART_UDF.USED_ON,
        CASE WHEN DR.DOCUMENT_ID = '3CXPhone for Windows.lnk' THEN '3CXPhone for Windows' ELSE DR.DOCUMENT_ID END AS DOCUMENT_ID,
        D.REVISION_ID,
        CASE WHEN POL.VENDOR_PART_ID LIKE '%EXP%' THEN 1 END AS EXPEDITE,
        CASE WHEN V.ACTIVE_FLAG = 'Y' AND ISNULL(V.USER_1, '') = '' AND ISNULL(V.USER_2, '') = '' THEN NULL WHEN V.USER_1 = 'Y' AND ISNULL(V.USER_2, '') <> '' THEN V.USER_2 ELSE 'Not Approved Vendor' END AS SUPPLIER_APPROVAL,
        CASE WHEN V.ACTIVE_FLAG = 'Y' AND ISNULL(V.USER_1, '') = '' AND ISNULL(V.USER_2, '') = '' THEN NULL WHEN V.USER_1 = 'Y' AND ISNULL(V.USER_4, '') <> '' THEN V.USER_4 ELSE 'Not ITAR Approved' END AS ITAR_APPROVAL,
        CASE WHEN V.ACTIVE_FLAG = 'Y' AND ISNULL(V.USER_1, '') = '' AND ISNULL(V.USER_2, '') = '' THEN NULL WHEN V.USER_1 = 'Y' AND ISNULL(V.USER_5, '') <> '' THEN V.USER_5 ELSE 'Not DPD Approved' END AS DPD_APPROVAL,
        ISNULL(PART_UDF.HAS_PRT_LIMITED, 0) AS HasPrtLimited,
        ISNULL(VENDOR_UDF.HAS_VND_LIMITED, 0) AS HasVndLimited,
        IIF(ISNULL(VENDOR_UDF.HAS_VND_LIMITED, 0) = 1 AND ISNULL(PART_UDF.HAS_PRT_LIMITED, 0) = 0, 1, 0) AS IsFlaggedLimited,
        CASE
            WHEN PART_UDF.CONTROLLED_CODE = 'SPECIFICATION CONTROLLED' AND ISNULL(V.USER_2, '') = '' THEN 'Product must be manufactured by an approved supplier listed in stated specification'
            WHEN PART_UDF.CONTROLLED_CODE IN ('CONTROLLED', 'QPL CONTROLLED') AND ISNULL(V.USER_2, '') = '' THEN 'Controlled Products must be from an approved manufacturer'
            WHEN P.FABRICATED = 'Y' AND ISNULL(V.USER_2, '') = '' THEN 'Fabricated Products must be from an approved manufacturer'
            WHEN V.USER_2 = 'Disapproved' THEN 'Check Vendor ASL information'
            WHEN ISNULL(VENDOR_UDF.HAS_VND_LIMITED, 0) = 1 AND ISNULL(PART_UDF.HAS_PRT_LIMITED, 0) = 0 THEN 'Not a Limited Scope Part'
            WHEN PART_UDF.ITAR_PART = 1 AND ISNULL(V.USER_4, '') = '' THEN 'Not ITAR Approved'
        END AS PRINTMESSAGE,
        CASE WHEN PO.VENDOR_ID = 'TMXDIV' THEN 'The INCOTERMS(TM) 2000 for all orders from Buyer will be Free on Board (FOB).' END AS TMXMESSAGE,
        STUFF((
            SELECT CHAR(032) + X.DOCUMENT_ID
            FROM
            (
                SELECT
                    WORKORDER_BASE_ID,
                    WORKORDER_LOT_ID,
                    WORKORDER_SPLIT_ID,
                    WORKORDER_SUB_ID,
                    WORKORDER_TYPE,
                    SEQUENCE_NO,
                    DOCUMENT_ID
                FROM CTE_DOCS
                GROUP BY
                    WORKORDER_BASE_ID,
                    WORKORDER_LOT_ID,
                    WORKORDER_SPLIT_ID,
                    WORKORDER_SUB_ID,
                    WORKORDER_TYPE,
                    SEQUENCE_NO,
                    DOCUMENT_ID
            ) X
            WHERE
                (
                    X.WORKORDER_BASE_ID = POL.PART_ID
                    AND (
                        X.WORKORDER_SUB_ID = DSL.DEMAND_SUB_ID
                        OR (X.WORKORDER_SUB_ID = 0 AND X.SEQUENCE_NO = 0)
                    )
                    AND (X.SEQUENCE_NO = 0 OR X.SEQUENCE_NO = DSL.DEMAND_SEQ_NO)
                )
                OR
                (
                    X.WORKORDER_TYPE = 'W'
                    AND X.WORKORDER_BASE_ID = DSL.DEMAND_BASE_ID
                    AND X.WORKORDER_LOT_ID = DSL.DEMAND_LOT_ID
                    AND X.WORKORDER_SPLIT_ID = DSL.DEMAND_SPLIT_ID
                    AND X.WORKORDER_SUB_ID = DSL.DEMAND_SUB_ID
                )
            FOR XML PATH('')
        ), 1, 1, '') AS DOCUMENT,
        CAST(CAST(VB.BITS AS VARBINARY(MAX)) AS NVARCHAR(MAX)) AS SPECTAB_VERBIAGE,
        CAST(CAST(POB.BITS AS VARBINARY(MAX)) AS NVARCHAR(MAX)) AS PO_LONG_DESCRIPTION,
        CAST(CAST(PLB.BITS AS VARBINARY(MAX)) AS NVARCHAR(MAX)) AS POL_LONG_DESCRIPTION,
        CAST(CAST(PAB.BITS AS VARBINARY(MAX)) AS NVARCHAR(MAX)) AS PAB_LONG_DESCRIPTION,
        WoUDF.UDF_STRINGV_WO,
        DSL.UDF_WO,
        CASE WHEN P.STOCKED = 'Y' AND P.CONSUMABLE = 'Y' THEN 'STOCKED and CONSUMABLE' WHEN P.STOCKED = 'Y' THEN 'STOCKED' WHEN P.CONSUMABLE = 'Y' THEN 'CONSUMABLE' END AS Item,
        V.USER_2 AS Vendor_Approved,
        CASE WHEN PART_UDF.CONTROLLED_CODE IS NULL OR PART_UDF.CONTROLLED_CODE IN ('Not Controlled', '') THEN 0 ELSE 1 END AS Part_Controller_L,
        ISNULL(PART_UDF.SUPPLIER_CONTROLLED_DRAWING, 0) AS Supplier_Controlled_Drawing
    FROM PURCHASE_ORDER PO
    LEFT JOIN PURC_ORDER_LINE POL ON PO.ID = POL.PURC_ORDER_ID
    LEFT JOIN PART P ON POL.PART_ID = P.ID
    LEFT JOIN EMPLOYEE EE ON PO.BUYER = EE.USER_ID
    LEFT JOIN VENDOR V ON PO.VENDOR_ID = V.ID
    LEFT JOIN TERMS T ON T.ID = V.DEF_TERMS_ID
    LEFT JOIN SHIPTO_ADDRESS STA ON STA.ADDR_NO = PO.SHIPTO_ADDR_NO
    LEFT JOIN (SELECT *, 'W~' + DEMAND_BASE_ID + '~' + CAST(DEMAND_SPLIT_ID AS varchar(12)) + '~' + CAST(DEMAND_LOT_ID AS varchar(12)) + '~' + CAST(DEMAND_SUB_ID AS varchar(12)) + '~' + CAST(DEMAND_SEQ_NO AS varchar(12)) AS UDF_WO FROM DEMAND_SUPPLY_LINK) DSL ON POL.PURC_ORDER_ID = DSL.SUPPLY_BASE_ID AND POL.LINE_NO = DSL.SUPPLY_SEQ_NO AND DSL.SUPPLY_TYPE = 'PO' AND DSL.DEMAND_TYPE = 'OP'
    LEFT JOIN DOCUMENT_REFERENCE DR ON DR.ID = POL.PART_ID AND DR.SOURCE_TYPE = 'P'
    LEFT JOIN DOCUMENT D ON D.ID = DR.DOCUMENT_ID AND D.SITE_ID = 'SK01'
    LEFT JOIN CTE_UDF_VMPRTMNT PART_UDF ON PART_UDF.DOCUMENT_ID = POL.PART_ID
    LEFT JOIN CTE_UDF_VMVNDMNT VENDOR_UDF ON VENDOR_UDF.DOCUMENT_ID = PO.VENDOR_ID
    LEFT JOIN CTE_UDF_VMPURENT PO_UDF ON PO_UDF.DOCUMENT_ID = PO.ID
    LEFT JOIN PURC_ORDER_BINARY POB ON PO.ID = POB.PURC_ORDER_ID AND POB.TYPE = 'D'
    LEFT JOIN VENDOR_BINARY VB ON V.ID = VB.VENDOR_ID AND VB.TYPE = 'D'
    LEFT JOIN PURC_LINE_BINARY PLB ON POL.PURC_ORDER_ID = PLB.PURC_ORDER_ID AND POL.LINE_NO = PLB.PURC_ORDER_LINE_NO AND PLB.TYPE = 'D'
    LEFT JOIN PART_BINARY PAB ON POL.PART_ID = PAB.PART_ID AND PAB.TYPE = 'D'
    LEFT JOIN CTE_UDF_VMMFGWIN_OP WoUDF ON WoUDF.DOCUMENT_ID = DSL.UDF_WO
    WHERE PO.ID = @ORDER_ID
)
SELECT *,
    CASE WHEN SUPPLIER_APPROVAL = 'APPROVED' THEN '' ELSE '*** DO NOT SEND TO VENDOR ***' END AS WaterMark,
    CASE WHEN Supplier_Controlled_Drawing = 1 THEN 'Supplier Controlled Drawing' END AS Supplier_Controlled_Drawing_desc
FROM CTE_BASE;
