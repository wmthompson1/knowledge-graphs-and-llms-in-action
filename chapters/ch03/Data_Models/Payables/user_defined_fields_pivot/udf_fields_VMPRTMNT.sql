-- Pivoted USER_DEF_FIELDS for part-maintenance records.
-- Join on DOCUMENT_ID = PART.ID or PURC_ORDER_LINE.PART_ID.
SELECT
    DOCUMENT_ID,
    MAX(CASE WHEN ID = 'UDF-0000040' THEN BOOL_VAL END) AS ITAR_PART,
    MAX(CASE WHEN ID = 'UDF-0000082' THEN STRING_VAL END) AS CONTROLLED_CODE,
    MAX(CASE WHEN ID = 'UDF-0000084' THEN STRING_VAL END) AS CERT_REQ,
    MAX(CASE WHEN ID = 'UDF-0000085' THEN STRING_VAL END) AS USED_ON,
    MAX(CASE WHEN ID = 'UDF-0000091' THEN BOOL_VAL END) AS HAS_PRT_LIMITED,
    MAX(CASE WHEN ID = 'UDF-0000101' THEN STRING_VAL END) AS PART_QCNOTES,
    MAX(CASE WHEN ID = 'UDF-00115' THEN BOOL_VAL END) AS SUPPLIER_CONTROLLED_DRAWING
FROM Live.dbo.USER_DEF_FIELDS
WHERE PROGRAM_ID = 'VMPRTMNT'
GROUP BY DOCUMENT_ID;
