DECLARE @P1 nvarchar(255) = N'100T1435-7';
DECLARE @P2 nvarchar(255) = N'100T1435-7';
DECLARE @P3 nvarchar(255) = N'100T1435-7';
DECLARE @P4 nvarchar(255) = N'100T1435-7';
DECLARE @P5 nvarchar(255) = N'100T1435-7';
DECLARE @P6 nvarchar(255) = N'100T1435-7';
DECLARE @P7 nvarchar(255) = N'100T1435-7';

SELECT
    1 as WNT,
    W.STATUS,
    ISNULL(W.DESIRED_WANT_DATE, CONVERT(datetime, N'3999-12-31', 102)),
    W.DESIRED_QTY,
    W.RECEIVED_QTY,
    W.ALLOCATED_QTY,
    W.FULFILLED_QTY,
    W.TYPE,
    W.BASE_ID,
    W.LOT_ID,
    W.SPLIT_ID,
    W.SUB_ID,
    W.DESIRED_RLS_DATE,
    0,
    CONVERT(datetime, N'3999-12-31', 102),
    W.WAREHOUSE_ID,
    WBS_CODE,
    SITE_ID,
    W.USER_1,
    W.USER_2,
    W.USER_3,
    W.USER_4,
    W.USER_5,
    W.USER_6,
    W.USER_7,
    W.USER_8,
    W.USER_9,
    W.USER_10,
    0
FROM WORK_ORDER W
WHERE W.PART_ID = @P1
  AND W.SITE_ID IN (N'SK01')
  AND W.TYPE = N'W'
  AND W.SUB_ID = N'0'
  AND W.DESIRED_QTY > W.RECEIVED_QTY
  AND W.WBS_PROJECT = N'N'
  AND STATUS IN (N'R', N'S', N'U', N'F', N'H')

UNION

SELECT
    2 as WNT,
    W.STATUS,
    ISNULL(W.DESIRED_WANT_DATE, CONVERT(datetime, N'3999-12-31', 102)),
    CP.DESIRED_QTY,
    CP.RECEIVED_QTY,
    CP.ALLOCATED_QTY,
    CP.FULFILLED_QTY,
    W.TYPE,
    W.BASE_ID,
    W.LOT_ID,
    W.SPLIT_ID,
    W.SUB_ID,
    W.DESIRED_RLS_DATE,
    0,
    CONVERT(datetime, N'3999-12-31', 102),
    ISNULL(CP.WAREHOUSE_ID, W.WAREHOUSE_ID),
    W.WBS_CODE,
    W.SITE_ID,
    W.USER_1,
    W.USER_2,
    W.USER_3,
    W.USER_4,
    W.USER_5,
    W.USER_6,
    W.USER_7,
    W.USER_8,
    W.USER_9,
    W.USER_10,
    0
FROM WORK_ORDER W, CO_PRODUCT CP
WHERE CP.PART_ID = @P2
  AND CP.WORKORDER_TYPE = N'W'
  AND CP.WORKORDER_TYPE = W.TYPE
  AND CP.WORKORDER_BASE_ID = W.BASE_ID
  AND CP.WORKORDER_LOT_ID = W.LOT_ID
  AND CP.WORKORDER_SPLIT_ID = W.SPLIT_ID
  AND CP.WORKORDER_SUB_ID = W.SUB_ID
  AND W.SITE_ID IN (N'SK01')
  AND CP.DESIRED_QTY > CP.RECEIVED_QTY
  AND W.WBS_PROJECT = N'N'
  AND STATUS IN (N'R', N'S', N'U', N'F', N'H')

UNION

SELECT
    3 as WNT,
    O.STATUS,
    ISNULL(ISNULL(L.DESIRED_RECV_DATE, O.DESIRED_RECV_DATE), CONVERT(datetime, N'3999-12-31', 102)),
    L.ORDER_QTY,
    L.TOTAL_RECEIVED_QTY,
    L.ALLOCATED_QTY,
    L.FULFILLED_QTY,
    N'P',
    O.ID,
    LTRIM(STR(L.LINE_NO, 22, 0)),
    N'0',
    N'0',
    O.ORDER_DATE,
    0,
    CONVERT(datetime, DATENAME(YY, O.PRINTED_DATE) + N'-' + LEFT(DATENAME(MM, O.PRINTED_DATE), 3) + N'-' + DATENAME(DD, O.PRINTED_DATE)),
    ISNULL(L.WAREHOUSE_ID, O.WAREHOUSE_ID),
    L.WBS_CODE,
    L.SITE_ID,
    L.USER_1,
    L.USER_2,
    L.USER_3,
    L.USER_4,
    L.USER_5,
    L.USER_6,
    L.USER_7,
    L.USER_8,
    L.USER_9,
    L.USER_10,
    0
FROM PURC_ORDER_LINE L, PURCHASE_ORDER O
WHERE L.PURC_ORDER_ID = O.ID
  AND L.PART_ID = @P3
  AND L.SITE_ID IN (N'SK01')
  AND L.ORDER_QTY > L.TOTAL_RECEIVED_QTY
  AND L.SERVICE_ID IS NULL
  AND STATUS IN (N'R', N'S', N'U', N'F', N'H')
  AND LINE_STATUS = N'A'

UNION

SELECT
    3 as WNT,
    O.STATUS,
    ISNULL(ISNULL(D.DESIRED_RECV_DATE, L.DESIRED_RECV_DATE), CONVERT(datetime, N'3999-12-31', 102)),
    D.ORDER_QTY,
    D.RECEIVED_QTY,
    D.ALLOCATED_QTY,
    D.FULFILLED_QTY,
    N'PD',
    O.ID,
    LTRIM(STR(L.LINE_NO, 22, 0)),
    N'0',
    N'0',
    O.ORDER_DATE,
    D.DEL_SCHED_LINE_NO,
    CONVERT(datetime, DATENAME(YY, O.PRINTED_DATE) + N'-' + LEFT(DATENAME(MM, O.PRINTED_DATE), 3) + N'-' + DATENAME(DD, O.PRINTED_DATE)),
    ISNULL(ISNULL(D.WAREHOUSE_ID, L.WAREHOUSE_ID), O.WAREHOUSE_ID),
    L.WBS_CODE,
    L.SITE_ID,
    D.USER_1,
    D.USER_2,
    N'',
    N'',
    N'',
    N'',
    N'',
    N'',
    N'',
    N'',
    D.DEL_SCHED_LINE_NO
FROM PURC_ORDER_LINE L, PURCHASE_ORDER O, PURC_LINE_DEL D
WHERE L.PURC_ORDER_ID = O.ID
  AND L.PART_ID = @P4
  AND L.SITE_ID IN (N'SK01')
  AND D.PURC_ORDER_ID = L.PURC_ORDER_ID
  AND D.PURC_ORDER_LINE_NO = L.LINE_NO
  AND D.ORDER_QTY > ISNULL(D.RECEIVED_QTY, 0)
  AND L.SERVICE_ID IS NULL
  AND STATUS IN (N'R', N'S', N'U', N'F', N'H')
  AND LINE_STATUS = N'A'

UNION

