; WITH cte_LastClockOut AS (
	SELECT A.WORKORDER_BASE_ID, A.WORKORDER_LOT_ID, A.WORKORDER_SPLIT_ID , A.WORKORDER_SUB_ID
		, A.WORKORDER_TYPE, A.LAST_CLOCK_OUT, MAX(OPERATION_SEQ_NO) AS LAST_OPERATION
	FROM (	
            SELECT LT.WORKORDER_BASE_ID, LT.WORKORDER_LOT_ID, LT.WORKORDER_SPLIT_ID
				, LT.WORKORDER_SUB_ID, LT.WORKORDER_TYPE, MAX(LT.CLOCK_OUT) AS LAST_CLOCK_OUT
			FROM LABOR_TICKET LT
			WHERE EXISTS (	SELECT 1 FROM #cte_wo WO
					WHERE LT.WORKORDER_BASE_ID = WO.BASE_ID AND LT.WORKORDER_LOT_ID = WO.LOT_ID
						AND LT.WORKORDER_SPLIT_ID = WO.SPLIT_ID AND LT.WORKORDER_SUB_ID = WO.SUB_ID
						AND LT.WORKORDER_TYPE = WO.[TYPE]
			)
			GROUP BY LT.WORKORDER_BASE_ID, LT.WORKORDER_LOT_ID, LT.WORKORDER_SPLIT_ID
				, LT.WORKORDER_SUB_ID, LT.WORKORDER_TYPE
		) A
	JOIN LABOR_TICKET LT ON A.WORKORDER_BASE_ID = LT.WORKORDER_BASE_ID AND A.WORKORDER_LOT_ID = LT.WORKORDER_LOT_ID
		AND A.WORKORDER_SPLIT_ID = LT.WORKORDER_SPLIT_ID AND A.WORKORDER_SUB_ID = LT.WORKORDER_SUB_ID
		AND A.WORKORDER_TYPE = LT.WORKORDER_TYPE AND A.LAST_CLOCK_OUT = LT.CLOCK_OUT
	GROUP BY A.WORKORDER_BASE_ID, A.WORKORDER_LOT_ID, A.WORKORDER_SPLIT_ID
		, A.WORKORDER_SUB_ID, A.WORKORDER_TYPE, A.LAST_CLOCK_OUT
)
select * from cte_LastClockOut;