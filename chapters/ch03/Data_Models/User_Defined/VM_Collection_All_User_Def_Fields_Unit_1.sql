
DECLARE @PROGRAM_ID NVARCHAR(50) = 'VMMFGWIN_OP'

IF OBJECT_ID('tempdb..#Results') IS NOT NULL DROP TABLE #Results;
SELECT
       1 AS CountOf
       , DOCUMENT_ID AS ID
    , MAX(CASE WHEN ID = 'UDF-0000048' THEN STRING_VAL ELSE NULL END) AS [TIME LIMIT  (Yes if Checked)]
    , MAX(CASE WHEN ID = 'UDF-0000074' THEN STRING_VAL ELSE NULL END) AS [Customer Specific Specs Line 1]
    , MAX(CASE WHEN ID = 'UDF-0000075' THEN STRING_VAL ELSE NULL END) AS [Customer Specific Specs Line 2]
    , MAX(CASE WHEN ID = 'UDF-0000076' THEN STRING_VAL ELSE NULL END) AS [Customer Specific Specs Line 3]
    , MAX(CASE WHEN ID = 'UDF-0000077' THEN STRING_VAL ELSE NULL END) AS [Customer Specific Specs Line 4]
    , MAX(CASE WHEN ID = 'UDF-0000078' THEN STRING_VAL ELSE NULL END) AS [Customer Specific Specs Line 5]
    , MAX(CASE WHEN ID = 'UDF-0000079' THEN STRING_VAL ELSE NULL END) AS [Customer Specific Specs Line 6]
    , MAX(CASE WHEN ID = 'UDF-0000080' THEN STRING_VAL ELSE NULL END) AS [Customer Specific Specs Line 7]
    , MAX(CASE WHEN ID = 'UDF-0000081' THEN STRING_VAL ELSE NULL END) AS [Customer Specific Specs Line 8]
    , MAX(CASE WHEN ID = 'UDF-0000089' THEN STRING_VAL ELSE NULL END) AS [Minimum Hours]
INTO #Results
FROM Live.dbo.USER_DEF_FIELDS
WHERE PROGRAM_ID = @PROGRAM_ID
AND DOCUMENT_ID IS NOT NULL
GROUP BY DOCUMENT_ID;
SELECT * FROM #Results;