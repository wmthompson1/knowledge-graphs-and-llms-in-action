SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED
SET DEADLOCK_PRIORITY LOW
IF OBJECT_ID('tempdb..#Results') IS NOT NULL DROP TABLE #Results
IF OBJECT_ID('tempdb..#VQ_SUPPLIER') IS NOT NULL DROP TABLE #VQ_SUPPLIER

declare @SUPPLIER nvarchar(max) = 'METTEC';
declare @STARTDATE datetime = '2026-01-01'
declare @ENDDATE datetime = getdate()



Select * 
into #VQ_SUPPLIER
from [sql-iqm-9].[iqm_baseline_app].dbo.VQ_SUPPLIER;

-- select * from #Results

-- ~22
SELECT NCM_ID
	, PO.DISPLAY_ID AS PRODUCTION_ORDER_ID
	, NCM.PO_NUMBER AS VENDOR_PO_NUM
	, O.DISPLAY_ID AS OPERATION_ID
	, NCM.REFERENCE_5 AS [CUSTOMER_REFERENCE]
	, NCM.NCM_TYPE
	, NCM.NCM_DATE
	, NCM.[STATUS]
	, NCM.DUE_DATE
	, NCM.CLOSED_DATE
	, NCM.BUSINESS_UNIT_ID
	, P.PRODUCT_ID
	, P.[NAME] AS PROD_ID_NAME
	, NCM.REFERENCE_1 AS [SPEC_SECT]
	, NCM.SK_AS_IS AS [ASIS_DIM]
	, NCM.SK_SHOULD_BE AS [SHOULD_BE_DIM]
	, NCM.[DESCRIPTION] AS NCM_DESC
	, ISNULL(NCM.SK_MFG_NCM_PROCESS, NCM.SK_FIN_NCM_PROCESS) AS [PROCESS]
	, ISNULL(NCM.SK_MFG_NCM_SUBPROCESS, NCM.SK_FIN_NCM_SUBPROCESS) AS [SUBPROCESS]
	, NCM.USER_DEFINED_3 AS [CATEGORY]
	, ISNULL(NCM.USER_DEFINED_4, NCM.USER_DEFINED_7) AS [DEFECT]
	, NCM.DISPOSITION_TYPE
	, DT.[DESCRIPTION] AS DISP_DESC
	, NCM.SK_ROOT_CAUSE_ANALYSIS AS CORRECTION
	, NCM.SK_ROOT_CAUSE AS CAUSE
	, S.SUPPLIER_ID
	, NCM.REFERENCE_6 AS [REWORK_QTY]
	, NCM.REFERENCE_7 AS [SCRAP_QTY]
	, NCM.REFERENCE_8 AS [OVERAGE_QTY]
	, NCM.REFERENCE_9 AS [RETURN_QTY]
	, NCM.REFERENCE_10 AS [ASIS_QTY]
FROM [SQL-BI-1].Datawarehouse.dbo.VQ_NONCONFORMANCE NCM
LEFT OUTER JOIN [SQL-BI-1].Datawarehouse.dbo.VQ_PRODUCT P
	ON P.RECORD_ID = NCM.PRODUCT_REC_ID
LEFT OUTER JOIN [SQL-BI-1].Datawarehouse.dbo.VQ_PRODUCTION_ORDER PO
	ON PO.RECORD_ID = NCM.PROD_ORDER_REC_ID
LEFT OUTER JOIN [SQL-BI-1].Datawarehouse.dbo.VQ_OPERATION O
	ON O.RECORD_ID = NCM.OPERATION_REC_ID
LEFT OUTER JOIN [SQL-BI-1].Datawarehouse.dbo.VQ_DISPOSITION_TYPE DT
	ON DT.[DISPOSITION_TYPE] = NCM.[DISPOSITION_TYPE]
LEFT OUTER JOIN #VQ_SUPPLIER S
	ON S.RECORD_ID = NCM.REPORTED_BY_SUPP_REC_ID
WHERE NCM.SITE_ID = 'SK01'
	AND NCM.NCM_TYPE = 'SUPPLIER - MAJOR'
    AND S.SUPPLIER_ID IN (@SUPPLIER)
	AND NCM.NCM_DATE >= @STARTDATE
	AND NCM.NCM_DATE <= @ENDDATE

UNION ALL

-- Quality database #2: SQL-Lab-2 / NCM
SELECT NCM.NCM_NUMBER AS NCM_ID
	, NCM.BASE_ID + '/' + NCM.LOT_ID 
		+ CASE WHEN NCM.SPLIT_ID = '0' OR NCM.SPLIT_ID IS NULL THEN '' ELSE '.' + NCM.SPLIT_ID END AS PRODUCTION_ORDER_ID
	, NCM.VENDOR_PO_NUMBER AS VENDOR_PO_NUM
	, NCM.OPERATION_ID AS OPERATION_ID
	, NCM.CUST_REF AS [CUSTOMER_REFERENCE]
	, NCM.NCM_TYPE_CODE AS NCM_TYPE
	, NCM.NCM_DATE
	, NCM.NCM_STATUS AS [STATUS]
	, CAST(NULL AS DATETIME) AS DUE_DATE
	, NCM.NCM_CLOSED_DATE AS CLOSED_DATE
	, CASE WHEN NCM.TAG_AREA = 'Finish' THEN 'FIN' ELSE NCM.TAG_AREA END AS BUSINESS_UNIT_ID
	, NCM.PART_ID AS PRODUCT_ID
	, P.DESCRIPTION AS PROD_ID_NAME
	, CAST(NULL AS NVARCHAR(255)) AS [SPEC_SECT]
	, NCM.AS_IS_DIMENSION AS [ASIS_DIM]
	, NCM.SHOULD_BE_DIMENSION AS [SHOULD_BE_DIM]
	, NCM.NCM_DESCRIPTION AS NCM_DESC
	, COALESCE(NCM.PROCESS_ID, '_BLANK') AS [PROCESS]
	, COALESCE(NCM.SUBPROCESS_ID, '_BLANK') AS [SUBPROCESS]
	, CAST(NULL AS NVARCHAR(50)) AS [CATEGORY]
	, NCM.DEFECT_ID AS [DEFECT]
	, NCM.DISPOSITION_TYPE_CODE AS DISPOSITION_TYPE
	, DT.DESCRIPTION AS DISP_DESC
	, NCM.CORRECTION_TEXT AS CORRECTION
	, NCM.ROOT_CAUSE_TEXT AS CAUSE
	, NCM.REPORTED_BY_SUPPLIER_ID AS SUPPLIER_ID  -- 
	, NCM.REWORK_QTY AS [REWORK_QTY]
	, NCM.SCRAP_QTY AS [SCRAP_QTY]
	, NCM.OVERAGE_QTY AS [OVERAGE_QTY]
	, NCM.RETURN_QTY AS [RETURN_QTY]
	, NCM.ACCEPTED_QTY_DISPOSITION AS [ASIS_QTY]
FROM [sql-lab-2].[NCM].[dbo].[NONCONFORMANCE] NCM WITH (NOLOCK)
LEFT OUTER JOIN [sql-lab-2].[NCM].[dbo].[DISPOSITION_TYPE] DT WITH (NOLOCK)
	ON DT.DISPOSITION_TYPE_CODE = NCM.DISPOSITION_TYPE_CODE
LEFT OUTER JOIN [sql-lab-2].[NCM].[dbo].[EMPLOYEE_LOOKUP] MADE_EE WITH (NOLOCK)
	ON MADE_EE.EMPLOYEE_ID = NCM.MADE_BY_EMPLOYEE_ID
LEFT OUTER JOIN [sql-lab-2].[NCM].[dbo].[EMPLOYEE_LOOKUP] ASSGN_EE WITH (NOLOCK)
	ON ASSGN_EE.EMPLOYEE_ID = NCM.ASSIGNED_TO_EMPLOYEE_ID
LEFT OUTER JOIN [sql-lab-2].[NCM].[dbo].[EMPLOYEE_LOOKUP] DISP_EE WITH (NOLOCK)
	ON DISP_EE.EMPLOYEE_ID = NCM.DISPOSITION_BY_EMPLOYEE_ID
LEFT OUTER JOIN [sql-lab-2].[NCM].[dbo].[EMPLOYEE_LOOKUP] DISP_ASSG WITH (NOLOCK)
	ON DISP_ASSG.EMPLOYEE_ID = NCM.DISPOSITION_ASSIGNED_TO_EMPLOYEE_ID
LEFT OUTER JOIN [sql-lab-2].[NCM].[dbo].[EMPLOYEE_LOOKUP] VERIFY_BY_EE WITH (NOLOCK)
	ON VERIFY_BY_EE.EMPLOYEE_ID = NCM.VERIFIED_BY_EMPLOYEE_ID
LEFT OUTER JOIN [sql-lab-2].[Live].[dbo].[PART] P WITH (NOLOCK)
	ON P.ID = NCM.PART_ID
WHERE NCM.NCM_TYPE_CODE = 'SUPPLIER - MAJOR'
	AND NCM.REPORTED_BY_SUPPLIER_ID IN (@SUPPLIER)
	AND NCM.NCM_DATE >= @STARTDATE
	AND NCM.NCM_DATE <= @ENDDATE
    ;