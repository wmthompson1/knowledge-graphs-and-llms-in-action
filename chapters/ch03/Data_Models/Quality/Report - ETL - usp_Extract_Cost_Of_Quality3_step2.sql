SELECT 'Rework' as CLASS
	, WO.IDX , WO.CHRONORDER , WO.DESCRIPT
	, MAX(WO.ACT_BURDEN_COST + WO.ACT_SERVICE_COST + WO.ACT_LABOR_COST + WO.ACT_MATERIAL_COST) AS [TOTAL WO COST]
	, SUM(
			ISNULL(OP.ACT_ATL_BUR_COST, ISNULL(OPARC.ACT_ATL_BUR_COST,0) ) + 
			ISNULL(OP.ACT_ATL_LAB_COST, ISNULL(OPARC.ACT_ATL_LAB_COST,0) ) + 
			ISNULL(OP.ACT_ATL_SER_COST, ISNULL(OPARC.ACT_ATL_SER_COST,0) )
		) AS [TOTAL OPERATION COST]
	, WO.CREATE_DATE, WO.CREATE_DATE AS POSTING_DATE , WO.PART_ID , NCM.NCM_ID
	, WO.BASE_ID, WO.LOT_ID, WO.SPLIT_ID, WO.SUB_ID, WO.[TYPE]
	, NCM.DISPLAY_ID AS PRODUCTION_ORDER_ID
	, NCM.ALT_ID_1 AS WORKORDER_TYPE
	, NCM.ALT_ID_2 AS WORKORDER_BASE_ID
	, NCM.ALT_ID_3 AS WORKORDER_LOT_ID
	, NCM.ALT_ID_4 AS WORKORDER_SPLIT_ID
	, NCM.ALT_ID_5 AS WORKORDER_SUB_ID
	, NCM.PO_NUMBER AS VENDOR_PO_NUM
	, NCM.LOT_SIZE, NCM.ACCEPTED, NCM.REJECTED, NCM.NCM_DATE, NCM.DUE_DATE
	, NCM.REFERENCE_1 AS [SPEC_SECT]
	, NCM.REFERENCE_2 AS [DRAW_REF]
	, NCM.REFERENCE_3 AS [ASIS_DIM]
	, NCM.REFERENCE_4 AS [SHOULD_BE_DIM]
	, COALESCE(NCM.SK_FIN_NCM_PROCESS, NCM.SK_MFG_NCM_PROCESS) AS [PROCESS]
	, COALESCE(NCM.SK_FIN_NCM_SUBPROCESS, NCM.SK_MFG_NCM_SUBPROCESS) AS [SUBPROCESS]
	, NCM.USER_DEFINED_3 AS [CATEGORY]
	, ISNULL(NCM.USER_DEFINED_4, NCM.USER_DEFINED_7) AS [DEFECT]
	, NCM.DISPOSITION_TYPE, NCM.DISP_DATE
	, NCM.REFERENCE_6 AS [REWORK_QTY]
	, NCM.REFERENCE_7 AS [SCRAP_QTY]
	, NCM.REFERENCE_8 AS [OVERAGE_QTY]
	, NCM.REFERENCE_9 AS [RETURN_QTY]
	, NCM.REFERENCE_10 AS [ASIS_QTY]
	, NCM.DISPOSITION, NCM.BUSINESS_UNIT_ID
	, DATEPART(WEEK,NCM.NCM_DATE) AS WEEK_NUM
	, NCM.PROCESSX AS PROCESSX
	, SR.USER_5 AS FACILITY
	, SR.USER_4 AS SUPERVISOR
	, SR.USER_7 AS SUBDEPT
INTO #RESULTS
FROM #REQUIRESET WO 
LEFT OUTER JOIN [SQL-Lab-2].live.dbo.[OPERATION] OP WITH (NOLOCK) ON OP.WORKORDER_BASE_ID = WO.BASE_ID
	AND OP.WORKORDER_LOT_ID = WO.LOT_ID AND OP.WORKORDER_SUB_ID = WO.SUB_ID
	AND OP.WORKORDER_SPLIT_ID = WO.SPLIT_ID AND OP.WORKORDER_TYPE = WO.[TYPE]
LEFT OUTER JOIN [SQL-Lab-2].[LIVEARC].[dbo].[OPERATION] OPARC WITH (NOLOCK) ON OPARC.WORKORDER_BASE_ID = WO.BASE_ID
	AND OPARC.WORKORDER_LOT_ID = WO.LOT_ID AND OPARC.WORKORDER_SUB_ID = WO.SUB_ID
	AND OPARC.WORKORDER_SPLIT_ID = WO.SPLIT_ID AND OPARC.WORKORDER_TYPE = WO.[TYPE]
LEFT JOIN #DATASETNCM NCM 
	ON WO.CHRONORDER = NCM.CHRONORDER
	AND WO.IDX = NCM.IDX
	AND WO.LOT_ID = NCM.ALT_ID_3
	AND WO.SPLIT_ID = NCM.ALT_ID_4 
LEFT JOIN ([VQ_OPERATION] VO JOIN [SQL-Lab-2].live.dbo.SHOP_RESOURCE SR ON VO.CONST_RESOURCE_ID = SR.ID)  
	ON NCM.OPERATION_REC_ID = VO.RECORD_ID 
WHERE (1=1)
GROUP BY WO.IDX, WO.CHRONORDER, WO.DESCRIPT, NCM.NCM_ID , WO.BASE_ID, WO.LOT_ID
	, WO.SPLIT_ID, WO.SUB_ID, WO.[TYPE], WO.CREATE_DATE, WO.PART_ID, NCM.DISPLAY_ID
	, NCM.ALT_ID_1, NCM.ALT_ID_2, NCM.ALT_ID_3, NCM.ALT_ID_4, NCM.ALT_ID_5, NCM.PO_NUMBER 
	, NCM.LOT_SIZE, NCM.ACCEPTED, NCM.REJECTED, NCM.NCM_DATE, NCM.DUE_DATE, NCM.REFERENCE_1 
	, NCM.REFERENCE_2, NCM.REFERENCE_3, NCM.REFERENCE_4, NCM.SK_FIN_NCM_PROCESS
	, NCM.SK_MFG_NCM_PROCESS, NCM.SK_FIN_NCM_SUBPROCESS, NCM.SK_MFG_NCM_SUBPROCESS
	, NCM.USER_DEFINED_3, NCM.USER_DEFINED_4, NCM.USER_DEFINED_7, NCM.DISPOSITION_TYPE
	, NCM.DISP_DATE, NCM.REFERENCE_6, NCM.REFERENCE_7, NCM.REFERENCE_8, NCM.REFERENCE_9 
	, NCM.REFERENCE_10, NCM.DISPOSITION, NCM.BUSINESS_UNIT_ID, NCM.PROCESSX
	, SR.USER_5, SR.USER_4, SR.USER_7 
ORDER BY WO.IDX, WO.CHRONORDER
