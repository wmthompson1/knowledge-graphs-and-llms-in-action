	-- Quality database #2: SQL-Lab-2 / NCM.
	SELECT IDX = DATAWAREHOUSE.MANAGEDDATA.FN_PARSE_NUMERIC(NCM.BASE_ID)
		, WO.[TYPE]
		, NCM.BASE_ID, NCM.LOT_ID, NCM.SPLIT_ID, NCM.SUB_ID
		, NCM.NCM_NUMBER, NCM.NONCONFORMANCE_ID, NCM.ACCEPTED, NCM.TAG_AREA
		, NCM.DISPOSITION_NOTES, NCM.DISPOSITION_TYPE_CODE, NCM.DISPOSITION_DATE
		, CAST(NULL AS datetime2) DUE_DATE, NCM.LOT_SIZE, NCM.NCM_DATE
		, NCM.NCM_NUMBER, NCM.NCM_TYPE_CODE, NCM.VENDOR_PO_NUMBER
		, CAST(NULL AS nvarchar(32)) REFERENCE_1 -- no target SPEC_SECT field
		, CAST(NULL AS numeric) REFERENCE_10 -- no target ASIS_QTY field
		, CAST(NULL AS nvarchar(32)) REFERENCE_2 -- no target DRAW_REF field
		, NCM.AS_IS_DIMENSION -- AS [ASIS_DIM]
		, NCM.SHOULD_BE_DIMENSION -- AS [SHOULD_BE_DIM]
		, NCM.REWORK_QTY -- AS [REWORK_QTY]
		, NCM.SCRAP_QTY -- AS [SCRAP_QTY]
		, NCM.OVERAGE_QTY -- AS [OVERAGE_QTY]
		, NCM.RETURN_QTY -- AS [RETURN_QTY]
		, NCM.REJECTED
		, CASE WHEN NCM.TAG_AREA = 'FIN' THEN NCM.PROCESS_ID END
		, CASE WHEN NCM.TAG_AREA = 'FIN' THEN NCM.SUBPROCESS_ID END
		, CASE WHEN NCM.TAG_AREA = 'MFG' THEN NCM.PROCESS_ID END
		, CASE WHEN NCM.TAG_AREA = 'MFG' THEN NCM.SUBPROCESS_ID END
		, CAST(NULL AS nvarchar(16)) USER_DEFINED_3 -- no target CATEGORY field
		, CASE WHEN NCM.TAG_AREA = 'FIN' THEN NCM.DEFECT_ID END
		, CASE WHEN NCM.TAG_AREA = 'MFG' THEN NCM.DEFECT_ID END
		, NCM.PART_ID
		, NCM.PROCESS_ID PROCESSX
		, CASE WHEN NCM.PROCESS_ID = 'PAINT' THEN 1 ELSE 0 END ISPAINT
		, CAST(NULL AS bigint) OPERATION_REC_ID
	FROM [SQL-Lab-2].live.dbo.WORK_ORDER WO WITH (NOLOCK)
	JOIN [SQL-Lab-2].[NCM].[dbo].[NONCONFORMANCE] NCM WITH (NOLOCK)
		ON NCM.BASE_ID = WO.BASE_ID
		AND NCM.LOT_ID = WO.LOT_ID
		AND NCM.SPLIT_ID = WO.SPLIT_ID
		AND NCM.SUB_ID = WO.SUB_ID
	WHERE 1=1
	
	AND NCM.DISPOSITION_TYPE_CODE NOT IN ('OVERAGE', 'NONDISCREPANT', 'NON-DISCREPANT', 'SCRAP')
	AND COALESCE(NCM.PROCESS_ID, '') NOT IN ('PENETRANT', 'NDT')
