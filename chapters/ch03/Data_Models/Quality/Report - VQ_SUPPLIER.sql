SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED
SET DEADLOCK_PRIORITY LOW
IF OBJECT_ID('tempdb..#Results') IS NOT NULL DROP TABLE #Results
IF OBJECT_ID('tempdb..#VQ_SUPPLIER') IS NOT NULL DROP TABLE #VQ_SUPPLIER


Select * 
into #VQ_SUPPLIER
from [sql-iqm-9].[iqm_baseline_app].dbo.VQ_SUPPLIER;

SELECT S.SUPPLIER_ID FROM #VQ_SUPPLIER s
LEFT OUTER JOIN [SQL-BI-1].Datawarehouse.dbo.VQ_NONCONFORMANCE NCM
	ON S.RECORD_ID = NCM.REPORTED_BY_SUPP_REC_ID
WHERE NCM.SITE_ID = 'SK01'
	AND NCM.NCM_TYPE = 'SUPPLIER - MAJOR'
GROUP BY SUPPLIER_ID

