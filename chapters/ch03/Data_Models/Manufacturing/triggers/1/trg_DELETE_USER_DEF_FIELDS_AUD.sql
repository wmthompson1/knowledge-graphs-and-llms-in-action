CREATE TRIGGER [dbo].[DELETE_USER_DEF_FIELDS_AUD] ON [dbo].[USER_DEF_FIELDS] FOR DELETE AS
SET NOCOUNT ON
DECLARE @U NVARCHAR(20),@TB NVARCHAR(50),@D DATETIME,@K NVARCHAR(255),@A NVARCHAR(15),@1 NVARCHAR(255),
@2 NVARCHAR(255),
@3 NVARCHAR(255),
@4 DECIMAL(22,0),
@5 DECIMAL(22,0),
@6 DECIMAL(22,4),
@7 DATETIME,
@8 DECIMAL(22,4),
@9 NVARCHAR(255)
SELECT @U=SYSTEM_USER,@TB='USER_DEF_FIELDS',@D=GetDate(),@A='DELETE'
DECLARE C1 CURSOR LOCAL FAST_FORWARD FOR 
	SELECT PROGRAM_ID,ID,DOCUMENT_ID,LINE_NO,DEL_LINE_NO,BOOL_VAL,DATE_VAL,NUMBER_VAL,STRING_VAL
	FROM  DELETED
OPEN C1
FETCH C1 INTO @1,@2,@3,@4,@5,@6,@7,@8,@9
WHILE @@fetch_status<>-1
BEGIN 
	SELECT @K=IsNull(@1,'') + '~' + IsNull(@2,'') + '~' + IsNull(@3,'') + '~' + IsNull(CAST(@4 AS NVARCHAR(50)),'') + '~' + IsNull(CAST(@5 AS NVARCHAR(50)),'')
	IF @1 IS NOT NULL INSERT INTO HISTORY_DATA VALUES(@U,@TB,'PROGRAM_ID',@D,@K,@A,@1,NULL)
	IF @2 IS NOT NULL INSERT INTO HISTORY_DATA VALUES(@U,@TB,'ID',@D,@K,@A,@2,NULL)
	IF @3 IS NOT NULL INSERT INTO HISTORY_DATA VALUES(@U,@TB,'DOCUMENT_ID',@D,@K,@A,@3,NULL)
	IF @6 IS NOT NULL INSERT INTO HISTORY_DATA VALUES(@U,@TB,'BOOL_VAL',@D,@K,@A,@6,NULL)
	IF @7 IS NOT NULL INSERT INTO HISTORY_DATA VALUES(@U,@TB,'DATE_VAL',@D,@K,@A,@7,NULL)
	IF @8 IS NOT NULL INSERT INTO HISTORY_DATA VALUES(@U,@TB,'NUMBER_VAL',@D,@K,@A,@8,NULL)
	IF @9 IS NOT NULL INSERT INTO HISTORY_DATA VALUES(@U,@TB,'STRING_VAL',@D,@K,@A,@9,NULL)
	FETCH C1 INTO @1,@2,@3,@4,@5,@6,@7,@8,@9
END 
GO

