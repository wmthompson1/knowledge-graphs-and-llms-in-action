/*****
 * KB0733942
 * This script is used to identify inventory transactions where the costed quantity does not match the actual quantity.
 * It also traces related inventory distribution and receipt records, as well as demand-supply links.
 * The focus is on the part with ID '151W7590-25'.
 *****/

SELECT * FROM INVENTORY_TRANS WHERE PART_ID = '151W7590-25' AND COSTED_QTY <> QTY

SELECT * FROM INV_TRANS_DIST WHERE IN_TRANS_ID IN 
(SELECT TRANSACTION_ID FROM INVENTORY_TRANS WHERE PART_ID = '151W7590-25' AND COSTED_QTY < > QTY)

SELECT * FROM INV_TRANS_DIST WHERE OUT_TRANS_ID IN 
(SELECT TRANSACTION_ID FROM INVENTORY_TRANS WHERE PART_ID = '151W7590-25' AND COSTED_QTY < > QTY)

SELECT * FROM INV_RECEIPT_DIST WHERE INV_TRANS_ID IN (SELECT TRANSACTION_ID FROM INVENTORY_TRANS WHERE
PART_ID = '151W7590-25' AND COSTED_QTY < > QTY)

--- 2
SELECT * FROM DEMAND_SUPPLY_LINK WHERE ID IN (SELECT DEMAND_SUPPLY_ID FROM INV_RECEIPT_DIST WHERE INV_TRANS_ID IN
(SELECT TRANSACTION_ID FROM INVENTORY_TRANS WHERE PART_ID = '151W7590-25' and COSTED_QTY <> QTY))

SELECT I1.PART_ID, I2.PART_ID,  I1.TRANSACTION_ID,  I2.TRANSACTION_ID
FROM INV_TRANS_DIST D, INVENTORY_TRANS I1, INVENTORY_TRANS I2
WHERE D.IN_TRANS_ID = I1.TRANSACTION_ID AND D.OUT_TRANS_ID = I2.TRANSACTION_ID AND I1.PART_ID != I2.PART_ID

SELECT I1.WAREHOUSE_ID, I2.WAREHOUSE_ID, I1.SITE_ID, I2.SITE_ID 
FROM INV_TRANS_DIST D, INVENTORY_TRANS I1, INVENTORY_TRANS I2 
WHERE D.IN_TRANS_ID = I1.TRANSACTION_ID AND D.OUT_TRANS_ID = I2.TRANSACTION_ID
 AND I1.SITE_ID = I2.SITE_ID